import assert from 'node:assert/strict'
import { begin } from './browser-flow.mjs'
import { verifyPublication } from './publication.mjs'

const { page, session, button, click, nav, read, notice, draft, reset, end } = await begin()
try {
  await page.goto(session.url)
  await reset()
  const seed = await read(),
    base = draft(seed)
  assert.equal(base.metrics.requested, 378)
  assert.equal(await page.locator('.week-grid .slot').count(), 168)
  await page.locator('.slot.filled').first().click()
  await page.getByRole('dialog').waitFor()
  await click('Close dialog')
  await page.locator('.slot.empty').first().click()
  assert.match(
    await page.getByRole('dialog').innerText(),
    /requires|missing|unavailable|needs|insufficient|short|restricted|eligible/i,
  )
  await click('Close dialog')
  await nav('Compare planners')
  await click('Teaching example')
  await click('Neutral example')
  await nav('What would help?')
  await page.getByRole('button', { name: /^Preview / }).first().click()
  await page.locator('.preview-panel').waitFor()
  assert.deepEqual(await read(), seed)
  await nav('Recipes')
  await page.getByLabel('Demo household').selectOption('H02')
  await nav('Weekly plan')
  await click('Approve plan')
  await notice('Plan approved')
  const approved = await read()
  await nav('Donations')
  await click('Paste donor offer')
  await click('Packaged chickpeas')
  await click('Parse offer')
  await button('Confirm the example product details').waitFor()
  assert.equal(await button('Mark reviewed').isDisabled(), true)
  const offer = (await read()).proposals.at(-1)
  assert.deepEqual((await read()).lots, seed.lots)
  await click('Confirm the example product details')
  await click('Save edits')
  await notice('Offer saved')
  await click('Mark reviewed')
  await notice('Offer reviewed')
  const savedBefore = await read()
  await click('Preview impact')
  await page.getByRole('heading', { name: 'If received as entered' }).waitFor()
  assert.deepEqual(await read(), savedBefore)
  await page.getByLabel('Sealed package count', { exact: true }).fill('8')
  await page.getByRole('button', { name: /Use package total/ }).click()
  assert.equal(await button('Confirm received').isDisabled(), true)
  await page.getByRole('checkbox', { name: /confirm these actual delivery differences/i }).check()
  await click('Confirm received')
  await notice('Receipt recorded')
  const received = await read()
  assert.equal(received.lots.length, seed.lots.length + 1)
  assert.equal(received.lots.at(-1).quantityBaseUnits, 1600)
  assert.equal(received.offerStatus[offer.id], 'received')
  assert.equal(received.approvedId, approved.approvedId)
  await click('Recalculate')
  await notice('Draft recalculated')
  const after = await read()
  assert.equal(after.receiptComparison.afterId, after.draftId)
  assert.equal(after.plans[after.receiptComparison.beforeId].id, base.id)
  assert.ok(draft(after).metrics.allocated >= base.metrics.allocated)
  await page.getByLabel('Impact household').selectOption('H02')
  await page.getByText('Friday collection box · exact contents', { exact: true }).click()
  await nav('Weekly plan')
  await click('Improve variety')
  await notice('Variety search complete')
  const improved = await read()
  assert.equal(improved.approvedId, approved.approvedId)
  assert.deepEqual(draft(improved).allocations.map(slot), draft(after).allocations.map(slot))
  await page.getByRole('region', { name: 'Changes before approval' }).waitFor()
  await click('Approve plan')
  await notice('Plan approved')
  await click('Household')
  await page.setViewportSize({ width: 390, height: 844 })
  await nav('Box contents')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.reload()
  assert.equal((await read()).approvedId, improved.draftId)
  assert.equal((await read()).lots.length, received.lots.length)
  await page.getByLabel('Demo household').selectOption('H01')
  await nav('Kitchen settings')
  await page.getByLabel('Number of people').fill('2')
  await click('Save changes')
  await notice('Household saved')
  await click('Food bank')
  await click('Recalculate')
  await notice('Draft recalculated')
  assert.equal(draft(await read()).metrics.requested, 399)
  console.log(
    'PASS ordinary portals, catalog and comparison, offer extraction and confirmation, hypothetical 12 versus actual 8 pouches, stock, boxes, fixed-slot variety, approval, narrow household and persistent reload.',
  )
} finally {
  await end()
}
function slot(a) {
  return [a.householdId, a.day, a.meal, a.portions]
}

await verifyPublication()
