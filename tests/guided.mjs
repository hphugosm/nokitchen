import assert from 'node:assert/strict'
import { begin } from './browser-flow.mjs'
const { page, session, button, click, nav, read, notice, reset, end } = await begin(1280)
const next = () =>
  page.getByRole('region', { name: 'Guided demo' }).getByRole('button', { name: 'Next' }).click()
async function inspectDraft() {
  await page.getByRole('heading', { name: 'Inspect the draft meal plan' }).waitFor()
  await page.getByRole('heading', { name: 'Weekly plan', exact: true }).waitFor()
  assert.equal(await button('Approve plan').isEnabled(), true)
  await click('Inspect assigned meal')
  await page.getByRole('dialog').getByText('Draft plan', { exact: true }).waitFor()
  await click('Close dialog')
}
try {
  await page.goto(session.url)
  await reset()
  await click('Approve plan')
  await notice('Plan approved')
  const original = await read()
  await click('Start guided demo')
  await inspectDraft()
  await next()
  await click('Restart')
  await page.getByText('Step 1 of 7').waitFor()
  await click('Exit')
  assert.deepEqual(await read(), original)
  await click('Start guided demo')
  await inspectDraft()
  await next()
  await click('Back')
  await inspectDraft()
  await next()
  if (await button('Paste donor offer').isVisible()) await click('Paste donor offer')
  await click('Packaged chickpeas')
  await click('Parse offer')
  await next()
  await click('Confirm the example product details')
  await click('Save edits')
  await click('Mark reviewed')
  await next()
  await click('Preview impact')
  await page.getByRole('heading', { name: 'If received as entered' }).waitFor()
  await next()
  await click('Confirm received')
  await click('Recalculate')
  await next()
  await click('Improve variety')
  await next()
  await click('Approve plan')
  await page.getByRole('heading', { name: 'Meal schedule', exact: true }).waitFor()
  await click('Inspect assigned meal')
  await page.getByRole('dialog').getByText('Approved', { exact: true }).waitFor()
  await click('Close dialog')
  await click('Open collection boxes')
  await page.locator('article.packing-box').first().waitFor()
  await click('Finish tour')
  assert.deepEqual(await read(), original)
  await click('Start guided demo')
  await inspectDraft()
  await next()
  await page.reload()
  await page.getByRole('heading', { name: 'Weekly plan', exact: true }).waitFor()
  assert.deepEqual(await read(), original)
  console.log(
    'PASS seven-step tour through reviewed paste, impact, receipt, recalculation, variety, approval, recipe and collection box. Back, Restart, Exit, Finish and reload preserved ordinary state.',
  )
} finally {
  await end()
}
